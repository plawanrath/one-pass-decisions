KERNEL = r"""/* Forward pass of the packed one-pass encoder. Fixed source: dimensions and offsets come from op_model.h.
 * Float operations mirror the NumPy reference one for one; integer dot products are exact. */
#include "op_model.h"
#include <math.h>
#include <pthread.h>
#include <stdlib.h>
#include <string.h>

#if defined(__ARM_FEATURE_DOTPROD) && OP_GROUP == 32 && !defined(OP_PORTABLE)
#include <arm_neon.h>
#define OP_SDOT 1
#else
#define OP_SDOT 0
#endif

#define W(off) ((const void *)(op_W + (off)))
static const float MAGIC = 12582912.0f;
static inline float rne(float x) { return (x + MAGIC) - MAGIC; }

static float op_expf(float x) {
  const float LOG2E = 1.4426950408889634f, LN2_HI = 0.693145751953125f, LN2_LO = 1.428606765330187e-06f;
  if (x < -87.0f) return 0.0f;
  float k = rne(x * LOG2E);
  float r = (x - k * LN2_HI) - k * LN2_LO;
  float p = 0.0013888889f;
  p = p * r + 0.008333334f; p = p * r + 0.041666668f; p = p * r + 0.16666667f;
  p = p * r + 0.5f;         p = p * r + 1.0f;         p = p * r + 1.0f;
  int ki = (int)k; if (ki < -126) ki = -126; if (ki > 127) ki = 127;
  union { uint32_t u; float f; } two_k; two_k.u = (uint32_t)(ki + 127) << 23;
  return p * two_k.f;
}

static float op_erff(float x) {
  const float P = 0.3275911f;
  float s = x < 0.0f ? -1.0f : 1.0f, a = x < 0.0f ? -x : x;
  float t = 1.0f / (1.0f + P * a);
  float p = 1.061405429f;
  p = p * t + -1.453152027f; p = p * t + 1.421413741f; p = p * t + -0.284496736f; p = p * t + 0.254829592f;
  return s * (1.0f - p * t * op_expf(-(a * a)));
}

static inline float op_gelu(float x) { return 0.5f * x * (1.0f + op_erff(x * 0.70710678118654752f)); }

static void norm(float *x, int n, int d, const float *w, const float *b) {
  for (int t = 0; t < n; t++) {
    float *row = x + (size_t)t * d, sum = 0.0f;
    for (int i = 0; i < d; i++) sum += row[i];
    float mean = sum / (float)d, var = 0.0f;
    for (int i = 0; i < d; i++) { float dx = row[i] - mean; var += dx * dx; }
    float inv = 1.0f / sqrtf(var / (float)d + OP_EPS);
    for (int i = 0; i < d; i++) row[i] = (row[i] - mean) * inv * w[i] + (b ? b[i] : 0.0f);
  }
}

static void quantize_rows(const float *x, int n, int d, int8_t *q, float *scale) {
  for (int t = 0; t < n; t++) {
    const float *row = x + (size_t)t * d;
    float amax = 0.0f;
    for (int i = 0; i < d; i++) { float a = row[i] < 0.0f ? -row[i] : row[i]; if (a > amax) amax = a; }
    float s = (amax < 1e-8f ? 1e-8f : amax) / 127.0f;
    scale[t] = s;
    for (int i = 0; i < d; i++) {
      float v = rne(row[i] / s);
      q[(size_t)t * d + i] = (int8_t)(v < -127.0f ? -127.0f : (v > 127.0f ? 127.0f : v));
    }
  }
}

static inline int32_t dot_group(const int8_t *a, const int8_t *b) {
  int32_t s = 0;
  for (int i = 0; i < OP_GROUP; i++) s += (int32_t)a[i] * (int32_t)b[i];
  return s;
}

static inline void unpack_row(const unsigned char *src, int in, int8_t *dst) {
#if OP_BITS == 8
  memcpy(dst, src, (size_t)in);
#else
  for (int i = 0; i < in / 2; i++) {
    int lo = src[i] & 0xF, hi = src[i] >> 4;
    dst[2 * i] = (int8_t)(lo >= 8 ? lo - 16 : lo);
    dst[2 * i + 1] = (int8_t)(hi >= 8 ? hi - 16 : hi);
  }
#endif
}

static int op_threads(void) {
  static int T = 0;
  if (!T) { const char *e = getenv("OP_THREADS"); T = e ? atoi(e) : 1; if (T < 1) T = 1; if (T > 64) T = 64; }
  return T;
}

typedef void (*range_fn)(const void *ctx, int a, int b);
struct par_job { range_fn fn; const void *ctx; int a, b; };
static void *par_run(void *p) { const struct par_job *j = (const struct par_job *)p; j->fn(j->ctx, j->a, j->b); return NULL; }

static void par_for(int n, range_fn fn, const void *ctx) {
  int T = op_threads();
  if (T > n) T = n;
  if (T <= 1) { fn(ctx, 0, n); return; }
  struct par_job J[64];
  pthread_t th[64];
  for (int i = 0; i < T; i++) {
    J[i] = (struct par_job){fn, ctx, (int)((long)n * i / T), (int)((long)n * (i + 1) / T)};
    if (i) pthread_create(&th[i], NULL, par_run, &J[i]);
  }
  par_run(&J[0]);
  for (int i = 1; i < T; i++) pthread_join(th[i], NULL);
}

struct lin_job { const int8_t *xq; const float *xs; int n, in, out; const unsigned char *lv; const float *gs; float *y; };

static inline const int8_t *row_levels(const struct lin_job *J, int o, int8_t *buf) {
  const size_t row_bytes = (size_t)J->in * OP_BITS / 8;
#if OP_BITS == 8
  (void)buf;
  return (const int8_t *)(J->lv + (size_t)o * row_bytes);
#else
  unpack_row(J->lv + (size_t)o * row_bytes, J->in, buf);
  return buf;
#endif
}

static void linear_one(const struct lin_job *J, int o, const int8_t *w) {
  const int groups = J->in / OP_GROUP;
  const float *g = J->gs + (size_t)o * groups;
  const size_t in = (size_t)J->in;
  int t = 0;
  for (; t + 4 <= J->n; t += 4) {
    const int8_t *x0 = J->xq + (size_t)t * in, *x1 = x0 + in, *x2 = x1 + in, *x3 = x2 + in;
    float a0 = 0.0f, a1 = 0.0f, a2 = 0.0f, a3 = 0.0f;
    for (int k = 0; k < groups; k++) {
      const int8_t *wk = w + (size_t)k * OP_GROUP;
      const size_t c = (size_t)k * OP_GROUP;
      a0 += (float)dot_group(wk, x0 + c) * g[k];
      a1 += (float)dot_group(wk, x1 + c) * g[k];
      a2 += (float)dot_group(wk, x2 + c) * g[k];
      a3 += (float)dot_group(wk, x3 + c) * g[k];
    }
    J->y[(size_t)t * J->out + o] = a0 * J->xs[t];
    J->y[(size_t)(t + 1) * J->out + o] = a1 * J->xs[t + 1];
    J->y[(size_t)(t + 2) * J->out + o] = a2 * J->xs[t + 2];
    J->y[(size_t)(t + 3) * J->out + o] = a3 * J->xs[t + 3];
  }
  for (; t < J->n; t++) {
    const int8_t *xr = J->xq + (size_t)t * J->in;
    float acc = 0.0f;
    for (int k = 0; k < groups; k++) acc += (float)dot_group(w + (size_t)k * OP_GROUP, xr + (size_t)k * OP_GROUP) * g[k];
    J->y[(size_t)t * J->out + o] = acc * J->xs[t];
  }
}

#if OP_SDOT
static inline int32x4_t sums4(int8x16_t w0, int8x16_t w1, const int8x16_t *xv) {
  const int32x4_t z = vdupq_n_s32(0);
  int32x4_t d0 = vdotq_s32(vdotq_s32(z, w0, xv[0]), w1, xv[1]);
  int32x4_t d1 = vdotq_s32(vdotq_s32(z, w0, xv[2]), w1, xv[3]);
  int32x4_t d2 = vdotq_s32(vdotq_s32(z, w0, xv[4]), w1, xv[5]);
  int32x4_t d3 = vdotq_s32(vdotq_s32(z, w0, xv[6]), w1, xv[7]);
  return vpaddq_s32(vpaddq_s32(d0, d1), vpaddq_s32(d2, d3));
}

static void linear_tile4(const struct lin_job *J, int o, const int8_t *const w[4]) {
  const int groups = J->in / OP_GROUP, n = J->n;
  const size_t in = (size_t)J->in;
  const float *g[4];
  for (int r = 0; r < 4; r++) g[r] = J->gs + (size_t)(o + r) * groups;
  for (int t = 0; t < n; t += 4) {
    const int8_t *x = J->xq + (size_t)t * in;
    float32x4_t acc[4] = {vdupq_n_f32(0.0f), vdupq_n_f32(0.0f), vdupq_n_f32(0.0f), vdupq_n_f32(0.0f)};
    for (int k = 0; k < groups; k++) {
      const size_t c = (size_t)k * OP_GROUP;
      int8x16_t xv[8];
      for (int i = 0; i < 4; i++) { xv[2 * i] = vld1q_s8(x + i * in + c); xv[2 * i + 1] = vld1q_s8(x + i * in + c + 16); }
      for (int r = 0; r < 4; r++) {
        const int32x4_t s = sums4(vld1q_s8(w[r] + c), vld1q_s8(w[r] + c + 16), xv);
        acc[r] = vaddq_f32(acc[r], vmulq_f32(vcvtq_f32_s32(s), vdupq_n_f32(g[r][k])));
      }
    }
    for (int r = 0; r < 4; r++) {
      float a[4];
      vst1q_f32(a, acc[r]);
      for (int i = 0; i < 4 && t + i < n; i++) J->y[(size_t)(t + i) * J->out + o + r] = a[i] * J->xs[t + i];
    }
  }
}
#endif

static void linear_rows(const void *arg, int o0, int o1) {
  const struct lin_job *J = (const struct lin_job *)arg;
  static _Thread_local int8_t buf[4][2 * OP_INTER > OP_D ? 2 * OP_INTER : OP_D];
  int o = o0;
#if OP_SDOT
  for (; o + 4 <= o1; o += 4) {
    const int8_t *w[4];
    for (int r = 0; r < 4; r++) w[r] = row_levels(J, o + r, buf[r]);
    linear_tile4(J, o, w);
  }
#endif
  for (; o < o1; o++) linear_one(J, o, row_levels(J, o, buf[0]));
}

static void linear(const int8_t *xq, const float *xs, int n, int in, int out, const unsigned char *lv, const float *gs, float *y) {
  const struct lin_job J = {xq, xs, n, in, out, lv, gs, y};
  par_for(out, linear_rows, &J);
}

/* work buffers, allocated once for OP_MAX_T tokens */
static float *X, *H, *QKV, *CTX, *U, *G, *Y, *XS;
static int8_t *XQ;
static const int32_t *POS, *BLK;

static void ensure_buffers(void) {
  if (X) return;
  const size_t T = OP_MAX_T;
  X = malloc(sizeof(float) * T * OP_D); H = malloc(sizeof(float) * T * OP_D);
  QKV = malloc(sizeof(float) * T * 3 * OP_D); CTX = malloc(sizeof(float) * T * OP_D);
  U = malloc(sizeof(float) * T * 2 * OP_INTER); G = malloc(sizeof(float) * T * OP_INTER);
  Y = malloc(sizeof(float) * T * OP_D); XS = malloc(sizeof(float) * T);
  XQ = malloc((size_t)(T + 4) * 2 * OP_INTER);
  memset(XQ, 0, (size_t)(T + 4) * 2 * OP_INTER);
}

static void lin(const float *x, int n, int in, int out, size_t lv, size_t gs, float *y) {
  quantize_rows(x, n, in, XQ, XS);
  linear(XQ, XS, n, in, out, (const unsigned char *)W(lv), (const float *)W(gs), y);
}

static void rotate(float *v, int p, const float *cos, const float *sin) {
  float tmp[OP_HD];
  const int h = OP_HD / 2;
  for (int i = 0; i < OP_HD; i++) {
    float rot = i < h ? -v[i + h] : v[i - h];
    tmp[i] = v[i] * cos[(size_t)p * OP_HD + i] + rot * sin[(size_t)p * OP_HD + i];
  }
  memcpy(v, tmp, sizeof tmp);
}

struct attn_job { int n, sliding; };

/* block rule: key j is visible to query i when j is a state token (blk 0) or shares i's block; local layers add the
 * position-distance window. Masked scores get -1e4 added, as in the reference. */
static void attn_heads(const void *arg, int h0, int h1) {
  const struct attn_job *A = (const struct attn_job *)arg;
  const int n = A->n, d = OP_D;
  float *att = malloc(sizeof(float) * (size_t)n);
  float acc[OP_HD];
  for (int hh = h0; hh < h1; hh++)
    for (int i = 0; i < n; i++) {
      const float *q = QKV + (size_t)i * 3 * d + (size_t)hh * OP_HD;
      const float *kb = QKV + d + (size_t)hh * OP_HD, *vb = QKV + 2 * d + (size_t)hh * OP_HD;
      int j = 0;
      for (; j + 4 <= n; j += 4) {
        const float *k0 = kb + (size_t)j * 3 * d, *k1 = k0 + 3 * d, *k2 = k1 + 3 * d, *k3 = k2 + 3 * d;
        float s0 = 0.0f, s1 = 0.0f, s2 = 0.0f, s3 = 0.0f;
        for (int e = 0; e < OP_HD; e++) { s0 += q[e] * k0[e]; s1 += q[e] * k1[e]; s2 += q[e] * k2[e]; s3 += q[e] * k3[e]; }
        att[j] = s0; att[j + 1] = s1; att[j + 2] = s2; att[j + 3] = s3;
      }
      for (; j < n; j++) {
        const float *k = kb + (size_t)j * 3 * d;
        float s = 0.0f;
        for (int e = 0; e < OP_HD; e++) s += q[e] * k[e];
        att[j] = s;
      }
      float m = -INFINITY;
      for (j = 0; j < n; j++) {
        float s = att[j] * OP_SCALE_QK;
        int allowed = (BLK[j] == 0) || (BLK[j] == BLK[i]);
        if (A->sliding) { int dp = POS[i] - POS[j]; if (dp < 0) dp = -dp; allowed = allowed && dp <= OP_WINDOW; }
        s = s + (allowed ? 0.0f : -1e4f);
        att[j] = s;
        if (s > m) m = s;
      }
      float z = 0.0f;
      for (j = 0; j < n; j++) { att[j] = op_expf(att[j] - m); z += att[j]; }
      for (j = 0; j < n; j++) att[j] = att[j] / z;
      for (int e = 0; e < OP_HD; e++) acc[e] = 0.0f;
      for (j = 0; j < n; j++) {
        const float a = att[j], *v = vb + (size_t)j * 3 * d;
        for (int e = 0; e < OP_HD; e++) acc[e] += a * v[e];
      }
      memcpy(CTX + (size_t)i * d + (size_t)hh * OP_HD, acc, sizeof acc);
    }
  free(att);
}

static void glu_tokens(const void *arg, int t0, int t1) {
  (void)arg;
  for (int t = t0; t < t1; t++)
    for (int i = 0; i < OP_INTER; i++)
      G[(size_t)t * OP_INTER + i] = op_gelu(U[(size_t)t * 2 * OP_INTER + i]) * U[(size_t)t * 2 * OP_INTER + OP_INTER + i];
}

int op_forward(const int32_t *ids, const int32_t *pos, const int32_t *blk, int n, const int32_t *markers, int m, float *scores) {
  if (n <= 0 || n > OP_MAX_T || m <= 0) return -1;
  ensure_buffers();
  POS = pos; BLK = blk;
  const int d = OP_D;
  const int8_t *tl = (const int8_t *)W(OP_OFF_TOK_LEVELS);
  const float *ts = (const float *)W(OP_OFF_TOK_SCALE);
  for (int t = 0; t < n; t++) {
    if (ids[t] < 0 || ids[t] >= OP_VOCAB || pos[t] < 0 || pos[t] >= OP_MAX_T) return -1;
    for (int i = 0; i < d; i++) X[(size_t)t * d + i] = (float)tl[(size_t)ids[t] * d + i] * ts[ids[t]];
  }
  norm(X, n, d, (const float *)W(OP_OFF_EMB_NORM), NULL);
  for (int l = 0; l < OP_LAYERS; l++) {
    const struct op_layer *L = &OP_LAYER[l];
    memcpy(H, X, sizeof(float) * (size_t)n * d);
    if (L->has_attn_norm) norm(H, n, d, (const float *)W(L->attn_norm), NULL);
    lin(H, n, d, 3 * d, L->qkv_l, L->qkv_s, QKV);
    const float *cos = (const float *)W(L->sliding ? OP_OFF_ROPE_SLIDE_COS : OP_OFF_ROPE_FULL_COS);
    const float *sin = (const float *)W(L->sliding ? OP_OFF_ROPE_SLIDE_SIN : OP_OFF_ROPE_FULL_SIN);
    for (int t = 0; t < n; t++)
      for (int hh = 0; hh < OP_HEADS; hh++) {
        rotate(QKV + (size_t)t * 3 * d + (size_t)hh * OP_HD, pos[t], cos, sin);
        rotate(QKV + (size_t)t * 3 * d + d + (size_t)hh * OP_HD, pos[t], cos, sin);
      }
    const struct attn_job A = {n, L->sliding};
    par_for(OP_HEADS, attn_heads, &A);
    lin(CTX, n, d, d, L->o_l, L->o_s, Y);
    for (size_t i = 0; i < (size_t)n * d; i++) X[i] = X[i] + Y[i];
    memcpy(H, X, sizeof(float) * (size_t)n * d);
    norm(H, n, d, (const float *)W(L->mlp_norm), NULL);
    lin(H, n, d, 2 * OP_INTER, L->wi_l, L->wi_s, U);
    par_for(n, glu_tokens, NULL);
    lin(G, n, OP_INTER, d, L->wo_l, L->wo_s, Y);
    for (size_t i = 0; i < (size_t)n * d; i++) X[i] = X[i] + Y[i];
  }
  norm(X, n, d, (const float *)W(OP_OFF_FINAL_NORM), NULL);
  /* scorer head at the marker positions */
  for (int k = 0; k < m; k++) {
    if (markers[k] < 0 || markers[k] >= n) return -1;
    memcpy(H + (size_t)k * d, X + (size_t)markers[k] * d, sizeof(float) * (size_t)d);
  }
  lin(H, m, d, d, OP_OFF_HEAD_LEVELS, OP_OFF_HEAD_SCALES, Y);
  const float *hb = (const float *)W(OP_OFF_HEAD_BIAS);
  for (int k = 0; k < m; k++)
    for (int i = 0; i < d; i++) { float v = Y[(size_t)k * d + i] + hb[i]; Y[(size_t)k * d + i] = op_gelu(v); }
  norm(Y, m, d, (const float *)W(OP_OFF_HEAD_NORM_W), (const float *)W(OP_OFF_HEAD_NORM_B));
  const float *wo = (const float *)W(OP_OFF_HEAD_OUT);
  for (int k = 0; k < m; k++) {
    float acc = 0.0f;
    for (int i = 0; i < d; i++) acc += Y[(size_t)k * d + i] * wo[i];
    scores[k] = acc + OP_HEAD_OUT_BIAS;
  }
  return 0;
}
"""

CLI = r"""/* One packed sequence per line: "n m id... pos... blk... marker..." -> marker scores as exact hex floats. */
#define _POSIX_C_SOURCE 200809L
#include <stdio.h>
#include <stdlib.h>
#include "op_model.h"

int main(void) {
  char *line = NULL;
  size_t cap = 0;
  int32_t *buf = malloc(sizeof(int32_t) * (3 * OP_MAX_T + 4096));
  float *scores = malloc(sizeof(float) * 4096);
  while (getline(&line, &cap, stdin) > 0) {
    int cnt = 0;
    char *p = line, *end;
    for (;;) {
      long v = strtol(p, &end, 10);
      if (end == p) break;
      buf[cnt++] = (int32_t)v;
      p = end;
    }
    if (cnt < 2) { printf("ERR\n"); fflush(stdout); continue; }
    int n = buf[0], m = buf[1];
    if (cnt != 2 + 3 * n + m) { printf("ERR\n"); fflush(stdout); continue; }
    const int32_t *ids = buf + 2, *pos = ids + n, *blk = pos + n, *mk = blk + n;
    if (op_forward(ids, pos, blk, n, mk, m, scores) != 0) { printf("ERR\n"); fflush(stdout); continue; }
    for (int k = 0; k < m; k++) printf(k ? " %a" : "%a", (double)scores[k]);
    printf("\n");
    fflush(stdout);
  }
  free(line); free(buf); free(scores);
  return 0;
}
"""


def cflags() -> list[str]:
    arch = ["-march=armv8.2-a+dotprod"] if platform.machine() in ("arm64", "aarch64") else ["-march=native"]
    return ["-O3", "-std=c11", "-ffp-contract=off", *arch]


def emit(p: MBPacked, out: str | Path) -> dict:
    assert p.bits in (4, 8), "the kernel ships 4- or 8-bit weights; float mode is for checking the reference only"
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    blob, off = build_blob(p)
    (out / "op_weights.bin").write_bytes(blob)
    (out / "op_weights.S").write_text(ASM)
    (out / "op_model.h").write_text(header(p, off))
    (out / "op_kernel.c").write_text(KERNEL)
    (out / "op_cli.c").write_text(CLI)
    man = {"bits": p.bits, "config": p.config, "weight_bytes": len(blob), "weights_sha256": hashlib.sha256(blob).hexdigest(),
           "kernel_sha256": hashlib.sha256(KERNEL.encode()).hexdigest()}
    (out / "manifest.json").write_text(json.dumps(man, indent=1) + "\n")
    return man


def compile_cli(out: str | Path) -> Path:
    out = Path(out)
    f = cflags()
    subprocess.run(["cc", *f, "-c", "op_weights.S", "-o", "op_weights.o"], cwd=out, check=True)
    subprocess.run(["cc", *f, "-c", "op_kernel.c", "-o", "op_kernel.o"], cwd=out, check=True)
    subprocess.run(["cc", *f, "op_cli.c", "op_kernel.o", "op_weights.o", "-o", "op_cli", "-lm", "-lpthread"], cwd=out, check=True)
    return out / "op_cli"


def format_line(ids, pos, blk, markers) -> str:
    return " ".join(str(int(v)) for v in ([len(ids), len(markers)] + list(ids) + list(pos) + list(blk) + list(markers)))


def parse_line(line: str) -> np.ndarray:
    return np.array([float.fromhex(x) for x in line.split()], dtype=np.float32)


def run_cli(exe: Path, lines: list[str], jobs: int = 1, threads: int = 1) -> list[str]:
    k = max(1, min(jobs, len(lines)))
    bounds = [round(i * len(lines) / k) for i in range(k + 1)]
    procs = []
    for a, b in zip(bounds, bounds[1:]):
        pr = subprocess.Popen([str(exe)], stdin=subprocess.PIPE, stdout=subprocess.PIPE, env={**os.environ, "OP_THREADS": str(threads)})
        pr.stdin.write(("\n".join(lines[a:b]) + "\n").encode())
        pr.stdin.close()
        procs.append(pr)
    out = []
    for pr in procs:
        out.extend(pr.stdout.read().decode().splitlines())
        assert pr.wait() == 0
    assert len(out) == len(lines)
    return out


class CompiledPath:
    """Serve packed layouts through the compiled binary (one sequence per process call, persistent process)."""

    def __init__(self, exe: Path, threads: int = 1):
        self.exe = Path(exe)
        self.threads = threads
        self.proc = subprocess.Popen([str(self.exe)], stdin=subprocess.PIPE, stdout=subprocess.PIPE, env={**os.environ, "OP_THREADS": str(threads)}, bufsize=0)

    def scores(self, ids, pos, blk, markers) -> np.ndarray:
        self.proc.stdin.write((format_line(ids, pos, blk, markers) + "\n").encode())
        self.proc.stdin.flush()
        return parse_line(self.proc.stdout.readline().decode())

    def close(self):
        self.proc.stdin.close()
        self.proc.wait()
