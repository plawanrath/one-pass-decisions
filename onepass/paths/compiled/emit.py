"""Emit a native kernel for the packed one-pass encoder: weights as a linked constant, C that matches the reference.

Output directory contents:
  op_weights.bin   every tensor the kernel reads, in the shipped precision, 64-byte aligned
  op_weights.S     places op_weights.bin in a read-only section under the symbol `op_W`
  op_model.h       dimensions, layer types, and the byte offset of every tensor inside op_W
  op_kernel.c      the forward pass over one packed sequence (ids, positions, block ids, marker positions)
  op_cli.c         line driver: "n m ids.. pos.. blk.. markers.." in, marker scores out as exact hex floats
Every floating-point operation is performed in the order `reference.forward` performs it, so outputs are bit-identical
to the reference on any IEEE-754 machine that honours -ffp-contract=off. Integer dot products may be vectorized freely.
"""
